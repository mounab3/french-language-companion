# This is the main application file.
#
# Streamlit creates the web interface.
# The user interacts with this page through their browser.
#
# The application communicates with:
#
#      Streamlit
#          ↓
#       Python
#          ↓
#        ai.py
#          ↓
#        Ollama
#          ↓
#        Gemma 
#
# ============================================================


import streamlit as st

# Import the two AI functions in ai.py.
#
# generate_exercise() → creates a French exercise
# check_answer()     → checks the learner's answer
from ai import generate_exercise, check_answer


# ------------------------------------------------------------
# ⚙️ Streamlit page configuration
# ------------------------------------------------------------

# controls the browser tab title and icon.
st.set_page_config(
    page_title="French Language Companion",
    page_icon="🇫🇷"
)


# ------------------------------------------------------------
# 🏠 Main title
# ------------------------------------------------------------

st.title("🇫🇷 French Language Companion")

st.write(
    "Practice French with your AI learning companion."
)



# 💾 SESSION STATE
#
# Streamlit reruns the Python script when the user interacts
# with widgets such as buttons.
#
# session_state lets us remember information between those
# reruns.

# 📚 Store the current exercise


if "exercise" not in st.session_state:

    # At the beginning, there is no exercise.
    st.session_state.exercise = None



# 💡 Store the feedback


if "feedback" not in st.session_state:

    # At the beginning, there is no feedback.
    st.session_state.feedback = None



# 🎯 PRACTICE SELECTION


st.subheader("🎯 Choose your practice")


# 📚 Choose what the learner wants to practice


practice = st.radio(
    "What would you like to practice?",
    ["Grammar", "Orthography"]
)


# 🎓 Choose the French level


level = st.selectbox(
    "Choose your French level:",
    ["A1", "A2", "B1", "B2"]
)



# 🚀 GENERATE EXERCISE


if st.button("🚀 Generate Exercise"):

    # When the learner requests a new exercise,
    # we remove old feedback.
    st.session_state.feedback = None



    # ⏳ Show a loading message
   
    with st.spinner("🤖 Gemma is creating your exercise..."):

        # Ask the AI function to generate an exercise
        # using the selected level and practice type.
        st.session_state.exercise = generate_exercise(
            level,
            practice
        )


# 📚 DISPLAY THE EXERCISE


# Only show this section if an exercise exists.
if st.session_state.exercise:

    st.subheader("📚 Your Exercise")

    # Display the exercise generated by Gemma.
    st.write(st.session_state.exercise)


    
    #  Student answer
  

    student_answer = st.text_input(
        "✏️ Your answer:"
    )


  
    #  Check Answer button


    if st.button("🔎 Check Answer"):


       
        # ⚠️ Make sure the learner actually entered something
        
        if student_answer.strip() == "":

            st.warning(
                "Please enter an answer first."
            )


        else:
            # ⏳ Ask Gemma to check the answer
            

            with st.spinner(
                "🤖 Gemma is checking your answer..."
            ):

                # Send the exercise and student's answer to check_answer() function.
                st.session_state.feedback = check_answer(
                    level,
                    practice,
                    st.session_state.exercise,
                    student_answer
                )


#  DISPLAY FEEDBACK


# If Gemma has returned feedback, display it.
if st.session_state.feedback:

    st.subheader("💡 Feedback")

    # Show Gemma's response.
    st.write(st.session_state.feedback)


    # ➡️ Start another exercise

    if st.button("➡️ New Exercise"):

        # Remove the previous exercise.
        st.session_state.exercise = None

        # Remove the previous feedback.
        st.session_state.feedback = None

        # Rerun the application so we return to the
        # exercise-selection state.
        st.rerun()