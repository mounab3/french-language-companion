# This file is responsible for communicating with Gemma.
#   Python → requests → Ollama → Gemma
#
# Ollama runs Gemma locally on the computer and provides
# an API that our Python program can communicate with.
# ============================================================


import requests

# ⚙️ Ollama configuration


# This is the address of Ollama's local API.
# Ollama normally listens on port 11434.
OLLAMA_URL = "http://localhost:11434/api/chat"

# Gemma model installed with Ollama.
MODEL = "gemma3:4b"


#  General function for talking to Gemma


def ask_gemma(prompt, max_tokens=120):
    """
    Send a prompt to Gemma and return Gemma's response.

    Parameters:
        prompt:
            The instruction/question we want to send to Gemma.

        max_tokens:
            Limits how much text Gemma generates.
            We keep this relatively small because our exercises
            should be short and this can also reduce unnecessary
            generation time.

    Returns:
        Gemma's response as a text string.
    """

    try:
        # 📡 Send a POST request to Ollama
    
        response = requests.post(

            # Ollama API endpoint
            OLLAMA_URL,

            # Data sent to Ollama
            json={

                # Tell Ollama which model to use
                "model": MODEL,

                # The conversation sent to Gemma
                "messages": [
                    {
                        "role": "user",
                        "content": prompt
                    }
                ],

                # We want the complete response at once
                # instead of receiving many small pieces.
                "stream": False,

                # Generation settings
                "options": {

                    # Limit the amount of text Gemma generates.
                    # This is useful for short learning exercises.
                    "num_predict": max_tokens
                }
            },

            # If Gemma takes too long, stop waiting after
            # 180 seconds and handle the problem below.
            timeout=180
        )

        # ✅ Check whether the HTTP request was successful
      
        # If Ollama returns an error such as 404 or 500, this line will raise an exception.
        
        response.raise_for_status()

        # 📦 Extract Gemma's actual answer
      
        # Ollama returns information in JSON format.
     
        # response → message → content
        
        return response.json()["message"]["content"]


    # ⏳ Gemma took too long
    except requests.exceptions.Timeout:

        return (
            "Gemma took too long to respond. "
            "Please try again."
        )


    # 🔌 Ollama cannot be reached

    except requests.exceptions.ConnectionError:

        return (
            "Ollama is not running. "
            "Please start Ollama first."
        )


    # ⚠️ Any other unexpected error

    except Exception as e:

        return f"An error occurred: {e}"


# 📚 Generate a French exercise


def generate_exercise(level, practice):
    """
    Ask Gemma to generate one French exercise.

    Parameters:
        level:
            The learner's CEFR level (A1, A2, B1, B2).

        practice:
            The type of practice (Grammar or Orthography).

    Returns:
        A generated French exercise.
    """

    # 📝 Prompt for the AI

    prompt = f"""

You are a French teacher.

Create ONE {practice} exercise for a {level} learner.

Rules:
- Write in French.
- Keep it appropriate for {level}.
- Give only ONE exercise.
- Do not give the answer.
- Do not explain pronunciation.
- Maximum 50 words.
"""

    # Send the prompt to Gemma.
    return ask_gemma(prompt, max_tokens=100)


# 🔎 Check the learner's answer


def check_answer(level, practice, exercise, student_answer):
    """
    Ask Gemma to evaluate the learner's answer.

    Parameters:
        level:
            Learner's CEFR level.

        practice:
            Grammar or Orthography.

        exercise:
            The original exercise generated by Gemma.

        student_answer:
            The answer written by the learner.

    Returns:
        Feedback from Gemma.
    """

    # 🧠 Prompt for answer checking
  
    prompt = f"""
You are a French teacher checking a student's answer.

Level: {level}
Practice: {practice}

Exercise:
{exercise}

Student answer:
{student_answer}

Respond with:
Correct: YES or NO
Explanation: one short explanation.
Rule: one short French rule.

Do not add anything else.
"""

    # Ask Gemma to evaluate the answer.
    return ask_gemma(prompt, max_tokens=100)